// The HealthTrace marker catalogue — the single source of truth for what can be
// tracked, in what unit, and what counts as a healthy value.
//
// Shape of a marker:
//   key          stable id, used by readings.markerKey. Never rename one.
//   name         full label; `short` is the compact label used in dense lists
//   category     one of data/categories.js
//   unit         the CANONICAL unit. Every reading is STORED in this unit and
//                converted only for display (see utils/units.js).
//   altUnit      optional second unit the user (or a lab report) may use
//   toAlt        canonical * toAlt = altUnit value
//   decimals     display precision
//   bands        reference bands, ASCENDING by `upTo`, last one `upTo: null`.
//                A value falls in the first band whose `upTo` it is <=.
//   bandsBySex   optional { male, female } override for sex-specific ranges
//   scale        [min, max] of the visual band bar; purely cosmetic
//   direction    'lower' / 'higher' / 'range' — which way is better, used for
//                phrasing trend deltas ("down 12 — moving the right way")
//   aliases      lowercase strings a lab report might use, for the text parser
//   derived      when set, the marker is computed (utils/derived.js), never
//                entered by hand
//   vital        true for things measured at home and logged often
//   about        one plain-English sentence shown on the marker detail screen
//
// Reference bands are GENERAL ADULT ranges drawn from common lab reporting
// conventions. Labs differ, and a range is not a diagnosis — the app says so
// wherever a status is shown, and every band is overridable per marker in
// Settings.

